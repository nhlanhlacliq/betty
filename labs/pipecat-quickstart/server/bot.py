"""pipecat-quickstart - Pipecat Voice Agent

This bot uses a cascade pipeline: Speech-to-Text → LLM → Text-to-Speech

Generated by Pipecat CLI

BETTY LAB (2026-10-19): the quickstart rewired for Betty, to feel a streamed voice pipeline before deciding whether
Pipecat earns a place in the app. Nothing here is used by the Betty apps.
- Deepgram (Speech-to-Text, streaming)
- Claude Haiku 5.5 with Betty's personality (betty_prompt.txt, exported from src/config/betty.ts)
- Deepgram Aura (Text-to-Speech, streaming). Chirp 3 HD needs a Google service-account file (not Betty's API key).
Keys are read from the repo's own .env (DEEPGRAM_API_KEY, VITE_ANTHROPIC_API_KEY): nothing is copied here.

Run the bot using::

    uv run bot.py
"""

import os
from pathlib import Path

from dotenv import load_dotenv
from loguru import logger
from pipecat.audio.vad.silero import SileroVADAnalyzer
from pipecat.frames.frames import LLMRunFrame
from pipecat.pipeline.pipeline import Pipeline
from pipecat.pipeline.worker import PipelineParams, PipelineWorker
from pipecat.processors.aggregators.llm_context import LLMContext
from pipecat.processors.aggregators.llm_response_universal import (
    LLMContextAggregatorPair,
    LLMUserAggregatorParams,
)
from pipecat.runner.types import RunnerArguments
from pipecat.runner.utils import create_transport
from pipecat.services.anthropic.llm import AnthropicLLMService, AnthropicThinkingConfig
from pipecat.services.deepgram.stt import DeepgramSTTService
from pipecat.services.deepgram.tts import DeepgramTTSService
from pipecat.transports.base_transport import BaseTransport, TransportParams
from pipecat.turns.user_start.min_words_user_turn_start_strategy import MinWordsUserTurnStartStrategy
from pipecat.turns.user_turn_strategies import UserTurnStrategies
from pipecat.transports.daily.transport import DailyParams
from pipecat.workers.runner import WorkerRunner

# Betty's keys live in the repo root .env (git-ignored); a local .env here, if any, wins.
load_dotenv(Path(__file__).resolve().parents[3] / ".env")
load_dotenv(override=True)
BETTY_PROMPT = (Path(__file__).parent / "betty_prompt.txt").read_text()


async def run_bot(transport: BaseTransport, runner_args: RunnerArguments) -> None:
    """Run the voice bot for this session.

    Args:
        transport: The transport for this session, built by ``create_transport``
            (or by hand for the dial-out/SIP production flows).
        runner_args: Runner session arguments. Carries the request ``body``
            (e.g. dial-out settings, SIP call details) and ``session_id``; the
            standard web/telephony pipelines don't need it.
    """
    logger.info("Starting bot")

    # Speech-to-Text service
    stt = DeepgramSTTService(api_key=os.getenv("DEEPGRAM_API_KEY"))

    # Text-to-Speech service: Deepgram Aura, streamed (BETTY_VOICE to try another, e.g. aura-2-thalia-en)
    tts = DeepgramTTSService(
        api_key=os.getenv("DEEPGRAM_API_KEY"),
        settings=DeepgramTTSService.Settings(voice=os.getenv("BETTY_VOICE", "aura-2-helena-en")),
    )

    # LLM service: Claude Haiku 5.5 as Betty. Thinking OFF explicitly: Haiku 5.5 thinks by default and Pipecat only
    # switches it off for Sonnet, which would add seconds before every answer. Her instructions are prompt-cached.
    llm = AnthropicLLMService(
        api_key=os.getenv("ANTHROPIC_API_KEY") or os.getenv("VITE_ANTHROPIC_API_KEY"),
        settings=AnthropicLLMService.Settings(
            model=os.getenv("BETTY_MODEL", "claude-haiku-5-5"),
            system_instruction=BETTY_PROMPT,
            enable_prompt_caching=True,
            max_tokens=200,
            thinking=AnthropicThinkingConfig(type="disabled"),
        ),
    )

    context = LLMContext()
    user_aggregator, assistant_aggregator = LLMContextAggregatorPair(
        context,
        user_params=LLMUserAggregatorParams(
            vad_analyzer=SileroVADAnalyzer(),
            # Interrupt her only on WORDS, not on sound (2026-10-19): on the phone's loudspeaker her own voice came back
            # through the mic, the default "any speech" start cut her off every few seconds (patchy audio) and, with no
            # words to answer, her old sentence played on. While she speaks: 2 words to interrupt; when she is quiet: 1.
            # Also right for the bike: wind and engine noise are not words.
            user_turn_strategies=UserTurnStrategies(start=[MinWordsUserTurnStartStrategy(min_words=2)]),
        ),
    )

    # Pipeline - assembled from reusable components
    pipeline = Pipeline(
        [
            transport.input(),
            stt,
            user_aggregator,
            llm,
            tts,
            transport.output(),
            assistant_aggregator,
        ]
    )

    worker = PipelineWorker(
        pipeline,
        params=PipelineParams(
            enable_metrics=True,
            enable_usage_metrics=True,
        ),
        observers=[],
    )

    runner = WorkerRunner(handle_sigint=runner_args.handle_sigint)

    await runner.add_workers(worker)

    @worker.rtvi.event_handler("on_client_ready")
    async def on_client_ready(rtvi):
        # Kick off the conversation
        context.add_message(
            {"role": "user", "content": "(The rider just connected. Greet him in one short sentence.)"}
        )
        await worker.queue_frames([LLMRunFrame()])

    @transport.event_handler("on_client_connected")
    async def on_client_connected(transport, client):
        logger.info("Client connected")

    @transport.event_handler("on_client_disconnected")
    async def on_client_disconnected(transport, client):
        logger.info("Client disconnected")
        await runner.cancel()

    await runner.run()


async def bot(runner_args: RunnerArguments):
    """Main bot entry point."""

    transport_params = {
        "daily": lambda: DailyParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
        ),
        "webrtc": lambda: TransportParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
        ),
    }

    transport = await create_transport(runner_args, transport_params)

    await run_bot(transport, runner_args)


if __name__ == "__main__":
    from pipecat.runner.run import main

    main()
