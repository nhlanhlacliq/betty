"""pipecat-quickstart - Pipecat Voice Agent

This bot uses a cascade pipeline: Speech-to-Text → LLM → Text-to-Speech

Generated by Pipecat CLI

BETTY LAB (2026-10-19): the quickstart rewired for Betty, to feel a streamed voice pipeline before deciding whether
Pipecat earns a place in the app. Nothing here is used by the Betty apps.
- Deepgram (Speech-to-Text, streaming)
- Claude Haiku 5.5 with Betty's personality (betty_prompt.txt, exported from src/config/betty.ts)
- Deepgram Aura (Text-to-Speech, streaming). Chirp 3 HD needs a Google service-account file (not Betty's API key).
Keys are read from the repo's own .env (DEEPGRAM_API_KEY, VITE_ANTHROPIC_API_KEY): nothing is copied here.

Run the bot using::

    uv run bot.py
"""

